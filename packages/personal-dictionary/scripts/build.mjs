#!/usr/bin/env node
/**
 * Assembles `dist/` — the publishable form of the correction engine.
 *
 * Why generate instead of copy
 * ----------------------------
 * The engine also ships inside the DSH plugin at `<repo>/lib/correct/`. Maintaining a second
 * hand-edited copy would drift, and a drifted safety layer is worse than no safety layer.
 * So there is exactly one source of truth — the plugin's `lib/correct/` — and this script
 * derives the package from it. Change the engine in one place; both consumers follow.
 *
 * The one thing that is *not* copied is `glossary.js`. The plugin's glossary is one person's
 * vocabulary (their products, their projects, their colleagues). Shipping it would leak it,
 * and it would be useless to anyone else. The package therefore generates a neutral, empty
 * glossary and expects every term to come from the caller.
 *
 * The build fails loudly rather than producing a broken package
 * ------------------------------------------------------------
 * Copying files is only half the job: if the engine grows an import the build does not know
 * about, the package would still be written and would explode at the caller's first
 * `import`. So after writing `dist/` this script imports it in a child process and runs a
 * real correction through it. A green build means the published artifact was executed.
 *
 * Usage: node scripts/build.mjs [--out dist] [--quiet]
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.join(HERE, '..');
const REPO = path.join(PKG, '..', '..');
const SOURCE = path.join(REPO, 'lib', 'correct');
const SOURCE_DATA = path.join(REPO, 'lib', 'data', 'pinyin-table.txt');

const args = process.argv.slice(2);
const outIdx = args.indexOf('--out');
const OUT = path.join(PKG, outIdx === -1 ? 'dist' : args[outIdx + 1]);
const quiet = args.includes('--quiet');
const log = (...a) => { if (!quiet) console.log(...a); };

/** Engine modules, copied verbatim. Names must match the engine's relative imports. */
const ENGINE = ['index.js', 'pinyin.js', 'latin.js'];

// ── guards ──────────────────────────────────────────────────────────────────────────

if (!fs.existsSync(SOURCE)) {
  fail(`engine not found at ${SOURCE}\n`
    + 'This package must be built from a checkout of the dsh-voice-personal repository.');
}
for (const f of ENGINE) {
  if (!fs.existsSync(path.join(SOURCE, f))) fail(`missing engine module: lib/correct/${f}`);
}
if (!fs.existsSync(SOURCE_DATA)) fail(`missing pinyin table: ${SOURCE_DATA}`);

/**
 * Refuse to publish an engine whose imports are not all in the copied set. `dist/` is
 * assembled by filename, so an import this list does not know about is a guaranteed
 * runtime failure for every consumer — catch it at build time instead.
 */
function checkImports() {
  const known = new Set([...ENGINE, 'glossary.js']);
  const missing = [];
  for (const f of ENGINE) {
    const src = fs.readFileSync(path.join(SOURCE, f), 'utf8');
    for (const m of src.matchAll(/from\s+['"](\.[^'"]+)['"]/g)) {
      const resolved = path.posix.normalize(path.posix.join('correct', m[1]));
      const base = resolved.split('/').pop();
      if (resolved.startsWith('..') || !known.has(base)) missing.push(`lib/correct/${f} imports ${m[1]}`);
    }
  }
  if (missing.length) {
    fail(`the engine imports modules this build does not ship:\n  ${missing.join('\n  ')}\n`
      + 'Add them to ENGINE (and to the copied data, if applicable) before publishing.');
  }
}

function fail(message) {
  console.error(`build failed: ${message}`);
  process.exit(1);
}

// ── assembly ────────────────────────────────────────────────────────────────────────

checkImports();

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'correct'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'data'), { recursive: true });

for (const f of ENGINE) {
  fs.copyFileSync(path.join(SOURCE, f), path.join(OUT, 'correct', f));
}
fs.copyFileSync(SOURCE_DATA, path.join(OUT, 'data', 'pinyin-table.txt'));

/**
 * The neutral glossary. Same shape as the plugin's, no personal content: every array is
 * empty, so an unconfigured dictionary corrects nothing but spacing. A library that
 * silently rewrote text using someone else's product names would be a bug, not a feature.
 */
fs.writeFileSync(path.join(OUT, 'correct', 'glossary.js'), `/**
 * Neutral glossary — generated by scripts/build.mjs, do not edit.
 *
 * This package ships no vocabulary of its own. Every term comes from the caller via
 * \`createDictionary({ terms })\`. The arrays are exported so the engine's shape is
 * unchanged from its upstream form and so callers can assert on emptiness.
 */

/** Canonical spellings. A caller supplies these; the package supplies none. */
export const TERMS = [];

/**
 * Explicit wrong -> right rewrites. Empty by design: plain string replacement over-reaches
 * on Chinese homophones, and the caller's own pairs belong in their own config.
 */
export const PAIRS = [];

/** Strings that must survive correction unchanged. The caller's test suite owns these. */
export const GUARDS = [];
`);

const tableBytes = fs.statSync(path.join(OUT, 'data', 'pinyin-table.txt')).size;
log(`assembled ${path.relative(PKG, OUT)}/`);
for (const f of ENGINE) log(`  correct/${f}`);
log(`  correct/glossary.js (generated, empty)`);
log(`  data/pinyin-table.txt (${(tableBytes / 1024).toFixed(0)} KiB)`);

// ── smoke test: execute the artifact that was just written ──────────────────────────

const smoke = `
import { createDictionary } from ${JSON.stringify(path.join(PKG, 'index.js'))};
const d = createDictionary({
  terms: [{ say: 'FlClash', heard: ['flcash'] }, { say: 'Harness', heard: ['哈里斯'] }],
});
const got = d.correct('帮我稳定我现在的flcash，这应该是哈里斯的工作吗');
const want = '帮我稳定我现在的 FlClash，这应该是 Harness 的工作吗';
if (got !== want) {
  console.error('got  ' + JSON.stringify(got));
  console.error('want ' + JSON.stringify(want));
  process.exit(1);
}
if (createDictionary({ terms: [] }).correct('人物关系很复杂') !== '人物关系很复杂') {
  console.error('an empty dictionary altered text');
  process.exit(1);
}
`;
try {
  execFileSync(process.execPath, ['--input-type=module', '--eval', smoke], { stdio: 'pipe' });
} catch (error) {
  fail(`the assembled package does not work:\n${error.stderr?.toString() ?? error.message}`);
}
log('smoke test passed (imported the package entry point and corrected a real string)');
